"""No-test repository orchestrator: scans risky sites, generates targeted pytest tests, and applies strict validation gates."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from flakeguard.llm.providers import BaseLLMProvider, get_provider
from flakeguard.notest.generator import GeneratedTest, generate_targeted_test
from flakeguard.notest.scanner import RiskySite, scan_repository_for_risky_sites
from flakeguard.notest.validator import ValidationResult, validate_generated_test
from flakeguard.runner.events import EventLogger


@dataclass
class NoTestScanSummary:
    """Summary of no-test scanning and test synthesis workflow."""

    repo_path: str
    risky_sites_count: int
    tests_generated_count: int
    tests_kept_count: int
    tests_rejected_count: int
    kept_tests: list[GeneratedTest] = field(default_factory=list)
    rejection_reasons: dict[str, str] = field(default_factory=dict)
    output_file: str | None = None


def generate_tests_for_repo(
    repo_path: Path,
    output_test_file: Path | None = None,
    max_tests: int = 5,
    k_shuffled_runs: int = 5,
    provider: BaseLLMProvider | None = None,
    event_logger: EventLogger | None = None,
) -> NoTestScanSummary:
    """Scan repo for risky sites, synthesize targeted pytest tests recording current behaviour, and keep validated tests.

    STRICT RULES:
    1. Generated tests explicitly state that they record current behaviour.
    2. A test is kept ONLY if it passes at HEAD, is deterministic over k shuffled runs, and kills mutants.
    """
    root = repo_path.resolve()

    if event_logger:
        event_logger.log(stage="generate", event_type="started", data={"repo": str(root)})

    # 1. Scan for risky sites
    sites = scan_repository_for_risky_sites(root)
    if event_logger:
        event_logger.log(
            stage="generate",
            event_type="progress",
            data={"risky_sites_found": len(sites)},
        )

    # Prioritize unique functions across risk categories
    seen_funcs: set[str] = set()
    candidate_sites: list[RiskySite] = []
    for s in sites:
        if s.function_name != "<module>" and s.function_name not in seen_funcs:
            seen_funcs.add(s.function_name)
            candidate_sites.append(s)
        if len(candidate_sites) >= max_tests:
            break

    kept_tests: list[GeneratedTest] = []
    rejections: dict[str, str] = {}
    llm = provider or get_provider(allow_cache_fallback=True)

    # 2. Generate and validate tests
    for site in candidate_sites:
        target_file = Path(site.file_path)
        if not target_file.is_file():
            continue

        source_code = target_file.read_text(encoding="utf-8")
        module_name = target_file.stem

        gen_test = generate_targeted_test(
            site=site,
            source_snippet=source_code,
            module_import_name=module_name,
            provider=llm,
        )

        # 3. Validate against strict multi-stage quality gate
        val_res: ValidationResult = validate_generated_test(
            repo_path=root,
            test=gen_test,
            k=k_shuffled_runs,
        )

        if val_res.kept:
            kept_tests.append(gen_test)
            if event_logger:
                event_logger.log(
                    stage="generate",
                    event_type="progress",
                    test_id=gen_test.test_name,
                    data={"status": "kept", "k_runs": val_res.k_runs},
                )
        else:
            rejections[gen_test.test_name] = val_res.rejection_reason or "Unknown rejection"
            if event_logger:
                event_logger.log(
                    stage="generate",
                    event_type="progress",
                    test_id=gen_test.test_name,
                    data={"status": "rejected", "reason": val_res.rejection_reason},
                )

    # 4. Write kept tests if destination provided
    written_path: str | None = None
    if kept_tests and output_test_file:
        out_p = output_test_file.resolve()
        out_p.parent.mkdir(parents=True, exist_ok=True)
        content_lines = [
            '"""Auto-generated targeted pytest tests recording current behaviour at HEAD."""',
            "# Generated by FlakeGuard (Step 6: No-test repo workflow)",
            "# State: Generated tests record current behaviour at HEAD.",
            "",
            *([t.test_code.strip() + "\n\n" for t in kept_tests]),
        ]
        out_p.write_text("\n".join(content_lines), encoding="utf-8")
        written_path = str(out_p)

    summary = NoTestScanSummary(
        repo_path=str(root),
        risky_sites_count=len(sites),
        tests_generated_count=len(candidate_sites),
        tests_kept_count=len(kept_tests),
        tests_rejected_count=len(rejections),
        kept_tests=kept_tests,
        rejection_reasons=rejections,
        output_file=written_path,
    )

    if event_logger:
        event_logger.log(
            stage="generate",
            event_type="result",
            data={
                "risky_sites": summary.risky_sites_count,
                "generated": summary.tests_generated_count,
                "kept": summary.tests_kept_count,
                "rejected": summary.tests_rejected_count,
            },
        )

    return summary

