"""GitHub REST API client for workflow runs, artifacts, and workflow_dispatch."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any
from urllib.error import HTTPError
from urllib.request import ProxyHandler, Request, build_opener

GITHUB_API_BASE = "https://api.github.com"


class GitHubClient:
    """REST client interacting with GitHub Actions APIs.

    Token lives server-side in GITHUB_TOKEN / GH_TOKEN env var, never in the browser.
    """

    def __init__(self, token: str | None = None) -> None:
        self.token = token or os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or ""
        self.opener = build_opener(ProxyHandler({}))

    def _headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "FlakeGuard-App/1.0",
        }
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        return headers

    def _request(self, method: str, path: str, payload: dict[str, Any] | None = None) -> Any:
        url = f"{GITHUB_API_BASE}{path}"
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        req = Request(url, data=data, headers=self._headers(), method=method)
        try:
            with self.opener.open(req, timeout=30.0) as resp:
                if resp.status == 204:
                    return None
                body = resp.read()
                return json.loads(body.decode("utf-8")) if body else {}
        except HTTPError as e:
            err_body = e.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"GitHub API {method} {path} returned {e.code}: {err_body}") from e

    def list_workflow_runs(self, owner: str, repo: str, workflow_id: str | None = None) -> list[dict[str, Any]]:
        """List workflow runs for a repository."""
        path = f"/repos/{owner}/{repo}/actions/runs"
        if workflow_id:
            path = f"/repos/{owner}/{repo}/actions/workflows/{workflow_id}/runs"
        res = self._request("GET", path)
        return res.get("workflow_runs", [])

    def get_run(self, owner: str, repo: str, run_id: int) -> dict[str, Any]:
        """Get details for a specific workflow run."""
        path = f"/repos/{owner}/{repo}/actions/runs/{run_id}"
        return self._request("GET", path)

    def list_run_artifacts(self, owner: str, repo: str, run_id: int) -> list[dict[str, Any]]:
        """List artifacts generated by a workflow run."""
        path = f"/repos/{owner}/{repo}/actions/runs/{run_id}/artifacts"
        res = self._request("GET", path)
        return res.get("artifacts", [])

    def download_artifact(self, owner: str, repo: str, artifact_id: int, dest_path: Path) -> Path:
        """Download artifact zip archive to dest_path."""
        path = f"/repos/{owner}/{repo}/actions/artifacts/{artifact_id}/zip"
        url = f"{GITHUB_API_BASE}{path}"
        req = Request(url, headers=self._headers(), method="GET")
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        with self.opener.open(req, timeout=60.0) as resp:
            dest_path.write_bytes(resp.read())
        return dest_path

    def dispatch_workflow(
        self,
        owner: str,
        repo: str,
        workflow_id: str,
        ref: str = "main",
        inputs: dict[str, Any] | None = None,
    ) -> bool:
        """Trigger a workflow_dispatch event."""
        path = f"/repos/{owner}/{repo}/actions/workflows/{workflow_id}/dispatches"
        payload = {"ref": ref, "inputs": inputs or {}}
        self._request("POST", path, payload)
        return True

